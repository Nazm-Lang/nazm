"""Write `toolchain/pipeline/runtime.nz` from the runtime's import registry
(`crates/nazm-runtime/src/lib.rs`, `IMPORTS`): each symbol LIR may import and its signature, as
the instruction text declares it (`plain (i64) -> ptr`). Run from the repository root whenever the
registry changes; `run.sh` checks the file is current."""
import re
import sys

WORD = {"I64": "i64", "I32": "i32", "Ptr": "ptr", "Bit": "bit", "F32": "f32", "F64": "f64"}
src = open("crates/nazm-runtime/src/lib.rs").read()
rows = []
for m in re.finditer(r'^\s*import!\("([^"]+)", \[([A-Za-z0-9, ]*)\], (None|Some\(Word::([A-Za-z0-9]+)\)),', src, re.M):
    name, params, ret = m.group(1), m.group(2), m.group(4)
    ps = ", ".join(WORD[p.strip()] for p in params.split(",") if p.strip())
    sig = "plain (" + ps + ")" + (" -> " + WORD[ret] if ret else "")
    rows.append(name + "|" + sig)
out = '''// Generated by `toolchain/pipeline/tests/runtime_table.py` from the runtime's import registry
// (`crates/nazm-runtime/src/lib.rs`, `IMPORTS`); do not edit. Each symbol LIR may import, and its
// signature as the instruction text declares it.

pub fn runtime_table() -> Str ! {} {
    "''' + "\\n".join(rows) + '''"
}
'''
target = "toolchain/pipeline/runtime.nz"
if len(sys.argv) > 1 and sys.argv[1] == "--check":
    sys.exit(0 if open(target).read() == out else 1)
open(target, "w").write(out)
