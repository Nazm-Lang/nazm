#!/usr/bin/env python3
"""Writes toolchain/commands/docsdata.nz: Nazm's own documentation corpus (the fourteen documents of
`crates/nazm-docs/src/manifest.rs`) as the repository holds them, so `nazm docs` with no `--root` answers from the
corpus the binary carries (R8 slice 12; the Rust binary answers from the checkout it was built from, which a release
archive does not have). `--root DIR` still reads DIR's `docs/`.

    gen-docsdata.py [REPO] > toolchain/commands/docsdata.nz
"""
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else '.'


def literal(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t') + '"'


manifest = open(os.path.join(root, 'crates/nazm-docs/src/manifest.rs'), encoding='utf-8').read()
paths = sorted(set(re.findall(r'"(docs/[^"]+)"', manifest)))
assert len(paths) == 14, paths
out = ['// Nazm\'s own documentation corpus, as the repository holds it (R8 slice 12): generated by',
       '// `toolchain/commands/tests/gen-docsdata.py`, never edited. `nazm docs` with no `--root` reads these.', '']
out += ['// The document at `path` (`docs/user/spec.md`), "" for a path the corpus does not hold.', 'pub fn dd_text(path: Str) -> Str {']
for i, p in enumerate(paths):
    out += ['    if path == "' + p + '" { return dd_doc' + str(i) + '() }']
out += ['    ""', '}', '']
for i, p in enumerate(paths):
    data = open(os.path.join(root, p), 'rb').read()
    text = data.decode('utf-8')
    assert '\r' not in text and '\0' not in text, p
    lines = text.split('\n')
    final = lines.pop()
    if final != '':
        lines.append(final)
    out += ['fn dd_doc' + str(i) + '() -> Str {', '    let l = strs_new()']
    out += ['    strs_push(l, ' + literal(x) + ')' for x in lines]
    out += ['    str_join(l, str_from_byte(10))' + (' + str_from_byte(10)' if final == '' else ''), '}', '']
sys.stdout.buffer.write('\n'.join(out).encode('utf-8'))
