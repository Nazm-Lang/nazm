#!/usr/bin/env python3
"""Writes toolchain/commands/mcptools.nz: what `nazm-mcp` answers to `tools/list`, tool by tool, and its
`instructions`, as the reference writes them (the input schemas are `schemars`'s derivations, the
output schemas the published ones with their keys sorted).

    gen-mcptools.py NAZM_MCP > toolchain/commands/mcptools.nz

`tests/run.sh mcp` compares `tools/list` byte for byte, so a table that has gone stale is a difference.
"""
import json
import subprocess
import sys


def literal(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


ini = {"jsonrpc": "2.0", "id": 1, "method": "initialize",
       "params": {"protocolVersion": "2025-06-18", "capabilities": {}, "clientInfo": {"name": "t", "version": "1"}}}
lst = {"jsonrpc": "2.0", "id": 2, "method": "tools/list"}
data = ''.join(json.dumps(m, separators=(',', ':')) + '\n' for m in (ini, {"jsonrpc": "2.0", "method": "notifications/initialized"}, lst)).encode()
p = subprocess.run([sys.argv[1], '--root', sys.argv[2] if len(sys.argv) > 2 else 'examples/max.nz'], input=data, capture_output=True, check=True)
rows = [json.loads(l) for l in p.stdout.decode().split('\n') if l]
rows.sort(key=lambda r: r['id'])
instructions = rows[0]['result']['instructions']
tools = rows[1]['result']['tools']

out = []
out.append('// What `nazm-mcp` answers to `initialize` and `tools/list`, as the reference writes them (R5, design D25):')
out.append('// generated by `tests/gen-mcptools.py` from the reference binary, so the table says what it says.')
out.append('')
out.append('pub fn mt_instructions() -> Str {')
out.append('    ' + literal(instructions))
out.append('}')
out.append('')
out.append('pub fn mt_count() -> Int { %d }' % len(tools))
out.append('')
out.append('pub fn mt_name(i: Int) -> Str {')
for i, t in enumerate(tools):
    out.append('    if i == %d { return %s }' % (i, literal(t['name'])))
out.append('    ""')
out.append('}')
out.append('')
for i, t in enumerate(tools):
    out.append('fn mt_tool_%d() -> Str {' % i)
    out.append('    ' + literal(json.dumps(t, separators=(',', ':'), ensure_ascii=False)))
    out.append('}')
    out.append('')
out.append('// The whole tool, as it is an element of `tools/list`.')
out.append('pub fn mt_tool(i: Int) -> Str {')
for i, t in enumerate(tools):
    out.append('    if i == %d { return mt_tool_%d() }' % (i, i))
out.append('    ""')
out.append('}')
sys.stdout.write('\n'.join(out) + '\n')
