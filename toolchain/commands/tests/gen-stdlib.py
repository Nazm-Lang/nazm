#!/usr/bin/env python3
"""Writes compiler/stdlib_data.nz: the standard library and the core prelude as the Rust compiler carries them
(`nazm-sema/src/stdlib.rs` and `prelude.rs`, `include_str!`), so the Nazm compiler needs no `NAZM_LIBRARY` and no
checkout (R8 slice 12). Each module is a function that joins its lines; `sd_std(name)` and `sd_prelude()` answer.
The library directory named by `NAZM_LIBRARY`, where one is named, still wins (`load.nz`).
`xtask/tests/generated.rs` fails when the committed file is not what this prints.

    gen-stdlib.py [REPO] > compiler/stdlib_data.nz
"""
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else '.'


def literal(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t').replace('\r', '\\r') + '"'


def body(path):
    text = open(os.path.join(root, path), encoding='utf-8', newline='').read()
    assert '\r' not in text and '\0' not in text
    lines = text.split('\n')
    last = lines.pop()
    out = ['    let l = strs_new();']
    for line in lines:
        out.append('    strs_push(l, ' + literal(line) + ');')
    # The text ends in a line break unless the file's last line has none.
    assert last == '', path
    out.append('    str_concat(str_join(l, str_from_byte(10)), str_from_byte(10))')
    return out


names = sorted(f[:-3] for f in os.listdir(os.path.join(root, 'library/std')) if f.endswith('.nz'))
out = ['// The standard library and the core prelude, as the repository holds them (R8 slice 12): generated by',
       '// `toolchain/commands/tests/gen-stdlib.py`, never edited. The Rust compiler carries the same bytes',
       '// (`nazm-sema/src/stdlib.rs`); with these the Nazm compiler reads no `NAZM_LIBRARY`. Statements end in `;` for the R2 parser.', '']
out += ['pub fn sd_names() -> Strs {', '    let s = strs_new();']
out += ['    strs_push(s, "' + n + '");' for n in names]
out += ['    s', '}', '']
out += ['// A standard module\'s source, "" for a name that is not one.', 'pub fn sd_std(name: Str) -> Str {']
for n in names:
    out += ['    if name == "' + n + '" { return sd_m_' + n + '(); }']
out += ['    ""', '}', '']
out += ['pub fn sd_prelude() -> Str {', *body('library/core/prelude.nz'), '}', '']
for n in names:
    out += ['fn sd_m_' + n + '() -> Str {', *body('library/std/' + n + '.nz'), '}', '']
sys.stdout.buffer.write('\n'.join(out).encode('utf-8'))
