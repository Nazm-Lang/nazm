#!/usr/bin/env python3
"""Writes toolchain/commands/capdata.nz: what `nazm capabilities` and `nazm capabilities --json` print, and the
`toolchain` member of `nazm inspect`, as the reference prints them (R8 slice 8). The inventory is read from the
Rust compiler's own tables (its builtin table, its types, its constructs, its targets and boards), which the
Nazm `nazm` does not hold; `tests/inspect.sh` compares the answers byte for byte, so a table that has gone
stale is a difference. Run from the repository's root with NAZM_LIBRARY set.

    gen-capdata.py NAZM > toolchain/commands/capdata.nz
"""
import json
import subprocess
import sys


def literal(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def run(*args):
    return subprocess.run([sys.argv[1], 'capabilities', *args], capture_output=True, check=True).stdout.decode()


text = run()
js = run('--json')
assert js.endswith('\n') and js.count('\n') == 1
assert text.endswith('\n')
inspected = json.loads(subprocess.run([sys.argv[1], 'inspect', 'examples/max.nz'], capture_output=True, check=True).stdout.decode())
toolchain = json.dumps(inspected['toolchain'], separators=(',', ':'), sort_keys=True, ensure_ascii=False)
out = []
out.append('// What `nazm capabilities` prints, as the reference prints it (R8 slice 8): generated by')
out.append('// `tests/gen-capdata.py` from the reference binary, so the table says what it says.')
out.append('')
out.append('pub fn cd_json() -> Str {')
out.append('    ' + literal(js[:-1]))
out.append('}')
out.append('')
out.append('// The `toolchain` member of `nazm inspect`: compact, its keys in order.')
out.append('pub fn cd_toolchain() -> Str {')
out.append('    ' + literal(toolchain))
out.append('}')
out.append('')
out.append('// The text, a line to each push; every line ends in a line break.')
out.append('pub fn cd_text() -> Str {')
out.append('    let lines = strs_new()')
for line in text[:-1].split('\n'):
    out.append('    strs_push(lines, ' + literal(line) + ')')
out.append('    str_join(lines, str_from_byte(10)) + str_from_byte(10)')
out.append('}')
sys.stdout.write('\n'.join(out) + '\n')
