#!/bin/sh
# Writes toolchain/commands/accelc.nz on standard output: the two C host programs of `nazm accel`
# (crates/nazm-cli/src/accel_host.c, accel_cpu.c, which accel.rs compiles into the Rust binary) as Nazm
# string literals. Regenerate the committed file with this script whenever either C file changes; nothing checks it yet.
#
#   toolchain/commands/tests/gen-accelc.sh > toolchain/commands/accelc.nz

set -eu
root=$(CDPATH= cd -- "$(dirname -- "$0")/../../.." && pwd)
dir="$root/crates/nazm-cli/src"

cat <<'OUT'
// The C host programs of `nazm accel` (R8 slice 11, task 10.2): the OpenCL provider's and the CPU provider's, as
// `crates/nazm-cli/src/accel.rs` holds them. Generated by toolchain/commands/tests/gen-accelc.sh from
// crates/nazm-cli/src/accel_host.c and accel_cpu.c; do not edit by hand.
OUT

emit() {
  name=$1
  f=$2
  printf '\npub fn %s() -> Str {\n    let l = strs_new()\n' "$name"
  if [ -z "$(tail -c 1 "$f")" ]; then last_nl=1; else last_nl=0; fi
  LC_ALL=C awk -v last_nl="$last_nl" '
    { lines[NR] = $0 }
    END {
      for (i = 1; i <= NR; i++) {
        s = lines[i]
        gsub(/\\/, "\\\\", s); gsub(/"/, "\\\"", s); gsub(/\t/, "\\t", s); gsub(/\r/, "\\r", s)
        nl = (i < NR || last_nl == 1) ? "\\n" : ""
        printf "    strs_push(l, \"%s%s\")\n", s, nl
      }
    }' "$f"
  printf '    str_join(l, "")\n}\n'
}

emit ac_host_source "$dir/accel_host.c"
emit ac_cpu_source "$dir/accel_cpu.c"
