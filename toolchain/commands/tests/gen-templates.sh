#!/bin/sh
# Writes toolchain/commands/init_templates.nz on standard output: every file of every `nazm init`
# template (crates/nazm-cli/templates, which `init.rs` compiles into the Rust binary), as Nazm string
# literals, in `init.rs`'s order — the templates as `TEMPLATES` lists them, each one's files sorted
# by their bytes. run.sh checks that the committed file is this script's output.
#
#   toolchain/commands/tests/gen-templates.sh > toolchain/commands/init_templates.nz

set -eu
root=$(CDPATH= cd -- "$(dirname -- "$0")/../../.." && pwd)
dir="$root/crates/nazm-cli/templates"

cat <<'EOF'
// Every file of every `nazm init` template, as `crates/nazm-cli/src/init.rs` holds them (R5, design
// D9). Generated by toolchain/commands/tests/gen-templates.sh from crates/nazm-cli/templates; do not
// edit by hand — run.sh fails when this file and the templates differ.

// Each file: its template, its path inside the project and its text, `{{name}}` still in it.
pub struct Templates {
    template: Strs,
    path: Strs,
    text: Strs,
}

// One file, from the lines collected in `lines`, which it empties.
fn tpl(t: Templates, template: Str, path: Str, lines: Strs) -> Int {
    strs_push(t.template, template)
    strs_push(t.path, path)
    strs_push(t.text, str_join(lines, ""))
    while strs_len(lines) > 0 { strs_pop(lines) }
    0
}

pub fn init_templates() -> Templates {
    let t = Templates(template: strs_new(), path: strs_new(), text: strs_new())
    let l = strs_new()
EOF

for t in cli library server embedded wasm contract; do
  (cd "$dir/$t" && find . -type f | sed 's|^\./||' | LC_ALL=C sort) | while IFS= read -r p; do
    f="$dir/$t/$p"
    # One literal per line of the file, `\`, `"`, tab and carriage return escaped; the last line
    # keeps its newline only if the file has one.
    if [ -z "$(tail -c 1 "$f")" ]; then last_nl=1; else last_nl=0; fi
    LC_ALL=C awk -v last_nl="$last_nl" '
      { lines[NR] = $0 }
      END {
        for (i = 1; i <= NR; i++) {
          s = lines[i]
          gsub(/\\/, "\\\\", s); gsub(/"/, "\\\"", s); gsub(/\t/, "\\t", s); gsub(/\r/, "\\r", s)
          nl = (i < NR || last_nl == 1) ? "\\n" : ""
          printf "    strs_push(l, \"%s%s\")\n", s, nl
        }
      }' "$f"
    printf '    tpl(t, "%s", "%s", l)\n' "$t" "$p"
  done
done

cat <<'EOF'
    t
}
EOF
