/// What a target needs done before `main`, as a unit of its own; nothing on POSIX (Gate 3). On
/// Windows, standard input, output and errors are put in binary mode, which the C runtime does not
/// start them in: `docs/spec.md` *Windows x86_64* has no line-ending translation.
#[must_use]
pub fn emit_init(target: SwitchTarget) -> Option<String> {
    (target == SwitchTarget::X86_64Windows).then(|| WINDOWS_INIT.to_owned())
}

const WINDOWS_INIT: &str = "; Generated by nazm build. Do not edit.
source_filename = \"init\"

declare i32 @_setmode(i32, i32)

@llvm.global_ctors = appending global [1 x { i32, ptr, ptr }] [{ i32, ptr, ptr } { i32 101, ptr @nz.win.init, ptr null }]

define internal void @nz.win.init() {
entry:
  %a = call i32 @_setmode(i32 0, i32 32768)
  %b = call i32 @_setmode(i32 1, i32 32768)
  %c = call i32 @_setmode(i32 2, i32 32768)
  ret void
}
";

/// The task stacks and the stack budget (Gate 3): the one part of the pool and of the stack check
/// that differs between operating systems, behind four functions the runtime calls.
///
/// - `nz_os_page_size() -> i64`: the page a guard is made of.
/// - `nz_os_stack_alloc(total, page) -> ptr`: `total` bytes, page-aligned, the lowest `page` of
///   them made inaccessible as a guard; null when either cannot be had (no guard, no stack).
/// - `nz_os_stack_free(base, total, page)`: the stack back; leaked rather than handed back
///   unreadable when its guard cannot be lifted (Q1-A1-10).
/// - `nz_os_stack_size() -> i64`: the main thread's stack, or 0 when the system will not say.
#[must_use]
pub fn emit_stack(target: SwitchTarget) -> String {
    let body = match target {
        SwitchTarget::X86_64Windows => WINDOWS_STACK,
        _ => POSIX_STACK,
    };
    format!("; Generated by nazm build. Do not edit.\nsource_filename = \"stack\"\n\n{body}")
}

const POSIX_STACK: &str = r"
declare i32 @getpagesize()
declare i32 @posix_memalign(ptr, i64, i64)
declare i32 @mprotect(ptr, i64, i32)
declare i32 @getrlimit(i32, ptr)
declare void @free(ptr)

define hidden i64 @nz_os_page_size() {
entry:
  %p = call i32 @getpagesize()
  %w = sext i32 %p to i64
  ret i64 %w
}

define hidden ptr @nz_os_stack_alloc(i64 %total, i64 %page) {
entry:
  %slot = alloca ptr, align 8
  %rc = call i32 @posix_memalign(ptr %slot, i64 %page, i64 %total)
  %bad = icmp ne i32 %rc, 0
  br i1 %bad, label %none, label %guard
guard:
  %base = load ptr, ptr %slot
  %g = call i32 @mprotect(ptr %base, i64 %page, i32 0)
  %gok = icmp eq i32 %g, 0
  br i1 %gok, label %done, label %unguarded
unguarded:
  call void @free(ptr %base)
  br label %none
none:
  ret ptr null
done:
  ret ptr %base
}

define hidden void @nz_os_stack_free(ptr %base, i64 %total, i64 %page) {
entry:
  %rw = call i32 @mprotect(ptr %base, i64 %page, i32 3)
  %ok = icmp eq i32 %rw, 0
  br i1 %ok, label %release, label %kept
release:
  call void @free(ptr %base)
  br label %kept
kept:
  ret void
}

define hidden i64 @nz_os_stack_size() {
entry:
  %rl = alloca [2 x i64], align 8
  ; RLIMIT_STACK is 3 on every POSIX target here, and struct rlimit is two 64-bit words.
  %rc = call i32 @getrlimit(i32 3, ptr %rl)
  %cur = load i64, ptr %rl
  %ok = icmp eq i32 %rc, 0
  %size = select i1 %ok, i64 %cur, i64 0
  ret i64 %size
}
";

/// Windows (Gate 3): pages from `VirtualAlloc`, the guard by `VirtualProtect`, the main thread's
/// stack from `GetCurrentThreadStackLimits` — the reservation the linker gave it.
const WINDOWS_STACK: &str = r"
declare void @GetSystemInfo(ptr)
declare ptr @VirtualAlloc(ptr, i64, i32, i32)
declare i32 @VirtualProtect(ptr, i64, i32, ptr)
declare i32 @VirtualFree(ptr, i64, i32)
declare void @GetCurrentThreadStackLimits(ptr, ptr)

define hidden i64 @nz_os_page_size() {
entry:
  ; SYSTEM_INFO is 48 bytes; dwPageSize is the 32-bit word at offset 4.
  %si = alloca [48 x i8], align 8
  call void @GetSystemInfo(ptr %si)
  %pp = getelementptr i8, ptr %si, i64 4
  %p = load i32, ptr %pp
  %w = zext i32 %p to i64
  ret i64 %w
}

define hidden ptr @nz_os_stack_alloc(i64 %total, i64 %page) {
entry:
  %old = alloca i32, align 4
  ; MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE.
  %base = call ptr @VirtualAlloc(ptr null, i64 %total, i32 12288, i32 4)
  %none = icmp eq ptr %base, null
  br i1 %none, label %fail, label %guard
guard:
  ; PAGE_NOACCESS.
  %g = call i32 @VirtualProtect(ptr %base, i64 %page, i32 1, ptr %old)
  %gok = icmp ne i32 %g, 0
  br i1 %gok, label %done, label %unguarded
unguarded:
  ; MEM_RELEASE, with a size of 0 as it requires.
  %r = call i32 @VirtualFree(ptr %base, i64 0, i32 32768)
  br label %fail
fail:
  ret ptr null
done:
  ret ptr %base
}

define hidden void @nz_os_stack_free(ptr %base, i64 %total, i64 %page) {
entry:
  ; The whole reservation goes, guard and all: released pages are never handed out unreadable.
  %r = call i32 @VirtualFree(ptr %base, i64 0, i32 32768)
  ret void
}

define hidden i64 @nz_os_stack_size() {
entry:
  %lo = alloca i64, align 8
  %hi = alloca i64, align 8
  call void @GetCurrentThreadStackLimits(ptr %lo, ptr %hi)
  %l = load i64, ptr %lo
  %h = load i64, ptr %hi
  %size = sub i64 %h, %l
  ret i64 %size
}
";

