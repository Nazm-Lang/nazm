//! Accelerator kernels (N67, `docs/architecture.md` §7.69): an eligible Nazm function, written as
//! an OpenCL C kernel that maps it over a sequence, carrying checked arithmetic exactly.
//!
//! Eligible: a pure function of `Int` and `Bool` values, calling only other eligible functions,
//! without recursion, built-ins, records, enums, closures or tasks. The kernel's own signature is
//! `(Int) -> Int`. Every checked operation keeps its failure: a work item that fails records
//! `index · 256 + site` with `atomic_min`, so the host reads the failure of the **lowest** failing
//! index — the one a sequential map would have stopped at, the work being pure — and its site.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use nazm_core::cir::ir::{
    ArithOp, Block, CmpOp, Const, Expr, ExprKind, Function, LocalId, Program, Stmt,
};
use nazm_core::sema::{FnId, Type};
use nazm_span::Span;

/// Why a function is not a kernel, with where.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Ineligible {
    pub function: String,
    pub at: Span,
    pub why: String,
}

/// One checked operation of the kernel, by its site number: what fails there and how.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Site {
    pub code: &'static str,
    pub message: String,
    pub at: Span,
}

/// A generated kernel: its OpenCL C source and its failure sites.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Kernel {
    pub source: String,
    pub sites: Vec<Site>,
    /// The functions it includes, the kernel's own first.
    pub functions: Vec<String>,
}

/// The kernel for `name`, or why not.
///
/// # Errors
///
/// The first reason, with its span, that `name` or a function it calls is not eligible.
pub fn kernel(
    program: &Program,
    root: Option<nazm_core::sema::ModuleId>,
    name: &str,
) -> Result<Kernel, Ineligible> {
    let entry = program
        .functions
        .iter()
        .find(|f| f.name == name && Some(f.module) == root)
        .ok_or_else(|| Ineligible {
            function: name.to_owned(),
            at: Span::synthetic(),
            why: format!("there is no function `{name}` in this module"),
        })?;
    let refuse = |f: &Function, at: Span, why: &str| Ineligible {
        function: f.name.clone(),
        at,
        why: why.to_owned(),
    };
    if entry.params != 1
        || entry.local(LocalId(0)).map(|l| l.ty) != Some(Type::Int)
        || entry.ret != Type::Int
    {
        return Err(refuse(
            entry,
            entry.name_span,
            "a kernel maps one `Int` to an `Int`: its signature must be `(Int) -> Int`",
        ));
    }
    // Every function the kernel reaches, in an order where each comes after what it calls.
    let mut order: Vec<FnId> = Vec::new();
    let mut visiting: Vec<FnId> = Vec::new();
    reach(program, entry.def, &mut order, &mut visiting)?;
    let mut g = Gen {
        out: String::new(),
        sites: Vec::new(),
        temps: 0,
    };
    let _ = writeln!(
        g.out,
        "// Generated by nazm accel (N67). One work item per element."
    );
    let _ = writeln!(
        g.out,
        "#define NZ_FAIL(site) {{ atomic_min(nz_fail, (int)(nz_index * 256 + (site))); *nz_failed = 1; return 0; }}"
    );
    for id in &order {
        let Some(f) = program.function(*id) else {
            continue;
        };
        g.function(f)?;
    }
    let _ = writeln!(
        g.out,
        "__kernel void nz_kernel(__global const long *nz_in, __global long *nz_out, __global int *nz_fail) {{\n\
         \x20 size_t nz_index = get_global_id(0);\n\
         \x20 int nz_flag = 0;\n\
         \x20 long r = {}(nz_in[nz_index], nz_fail, nz_index, &nz_flag);\n\
         \x20 nz_out[nz_index] = r;\n\
         }}",
        cname(entry)
    );
    Ok(Kernel {
        source: g.out,
        sites: g.sites,
        functions: order
            .iter()
            .rev()
            .filter_map(|i| program.function(*i).map(|f| f.name.clone()))
            .collect(),
    })
}

fn cname(f: &Function) -> String {
    format!("nz_f{}", f.def.index())
}

/// Depth-first over the calls `f` makes, refusing a cycle and anything ineligible.
fn reach(
    program: &Program,
    id: FnId,
    order: &mut Vec<FnId>,
    visiting: &mut Vec<FnId>,
) -> Result<(), Ineligible> {
    if order.contains(&id) {
        return Ok(());
    }
    let Some(f) = program.function(id) else {
        return Err(Ineligible {
            function: String::new(),
            at: Span::synthetic(),
            why: "a callee with no body".to_owned(),
        });
    };
    if visiting.contains(&id) {
        return Err(Ineligible {
            function: f.name.clone(),
            at: f.name_span,
            why: "it is in a call cycle; a kernel has no stack to recurse on".to_owned(),
        });
    }
    if f.foreign.is_some() {
        return Err(Ineligible {
            function: f.name.clone(),
            at: f.name_span,
            why: "it is a foreign function".to_owned(),
        });
    }
    if !f.effects.is_pure() {
        return Err(Ineligible {
            function: f.name.clone(),
            at: f.name_span,
            why: "it is not pure: a kernel cannot reach the host".to_owned(),
        });
    }
    if f.closure || f.type_params > 0 {
        return Err(Ineligible {
            function: f.name.clone(),
            at: f.name_span,
            why: "it is a closure or generic".to_owned(),
        });
    }
    for l in &f.locals {
        if !matches!(l.ty, Type::Int | Type::Bool) {
            return Err(Ineligible {
                function: f.name.clone(),
                at: l.at,
                why: "it has a value that is not an `Int` or a `Bool`; only those are device-safe"
                    .to_owned(),
            });
        }
    }
    if !matches!(f.ret, Type::Int | Type::Bool) {
        return Err(Ineligible {
            function: f.name.clone(),
            at: f.ret_span,
            why: "its result is not an `Int` or a `Bool`".to_owned(),
        });
    }
    visiting.push(id);
    let mut callees = BTreeSet::new();
    calls_in_block(&f.body, &mut callees);
    for c in callees {
        reach(program, c, order, visiting)?;
    }
    visiting.pop();
    order.push(id);
    Ok(())
}

fn calls_in_block(b: &Block, out: &mut BTreeSet<FnId>) {
    for s in &b.stmts {
        calls_in_stmt(s, out);
    }
    if let Some(t) = &b.tail {
        calls_in_expr(t, out);
    }
}

fn calls_in_stmt(s: &Stmt, out: &mut BTreeSet<FnId>) {
    match s {
        Stmt::Let { value, .. }
        | Stmt::Assign { value, .. }
        | Stmt::Eval(value)
        | Stmt::Return { value, .. } => {
            calls_in_expr(value, out);
        }
        Stmt::If {
            cond,
            then,
            otherwise,
            ..
        } => {
            calls_in_expr(cond, out);
            calls_in_block(then, out);
            if let Some(o) = otherwise {
                calls_in_block(o, out);
            }
        }
        Stmt::Loop { cond, body, .. } => {
            calls_in_expr(cond, out);
            calls_in_block(body, out);
        }
        Stmt::Block(b) => calls_in_block(b, out),
        _ => {}
    }
}

fn calls_in_expr(e: &Expr, out: &mut BTreeSet<FnId>) {
    match &e.kind {
        ExprKind::Call { callee, args, .. } => {
            out.insert(*callee);
            for a in args {
                calls_in_expr(a, out);
            }
        }
        ExprKind::Neg(x) => calls_in_expr(x, out),
        ExprKind::Arith { lhs, rhs, .. } | ExprKind::Compare { lhs, rhs, .. } => {
            calls_in_expr(lhs, out);
            calls_in_expr(rhs, out);
        }
        ExprKind::If {
            cond,
            then,
            otherwise,
        } => {
            calls_in_expr(cond, out);
            calls_in_block(then, out);
            calls_in_block(otherwise, out);
        }
        ExprKind::Block(b) => calls_in_block(b, out),
        _ => {}
    }
}

struct Gen {
    out: String,
    sites: Vec<Site>,
    temps: u32,
}

impl Gen {
    fn site(&mut self, code: &'static str, message: &str, at: Span) -> usize {
        self.sites.push(Site {
            code,
            message: message.to_owned(),
            at,
        });
        self.sites.len() - 1
    }

    fn temp(&mut self) -> String {
        self.temps += 1;
        format!("t{}", self.temps)
    }

    fn function(&mut self, f: &Function) -> Result<(), Ineligible> {
        let ty = |t: Type| if t == Type::Bool { "int" } else { "long" };
        let params: Vec<String> = (0..f.params)
            .map(|i| {
                format!(
                    "{} l{i}",
                    ty(f.local(LocalId(i)).map_or(Type::Int, |l| l.ty))
                )
            })
            .collect();
        let _ = writeln!(
            self.out,
            "static {} {}({}{}__global int *nz_fail, size_t nz_index, __private int *nz_failed) {{",
            ty(f.ret),
            cname(f),
            params.join(", "),
            if params.is_empty() { "" } else { ", " }
        );
        for (i, l) in f.locals.iter().enumerate().skip(f.params as usize) {
            let _ = writeln!(self.out, "  {} l{i} = 0;", ty(l.ty));
        }
        let mut body = String::new();
        let tail = self.block(f, &f.body, &mut body, 1)?;
        self.out.push_str(&body);
        if let Some(t) = tail {
            let _ = writeln!(self.out, "  return {t};");
        } else {
            let _ = writeln!(self.out, "  return 0;");
        }
        let _ = writeln!(self.out, "}}");
        Ok(())
    }

    fn refuse(f: &Function, at: Span, why: &str) -> Ineligible {
        Ineligible {
            function: f.name.clone(),
            at,
            why: why.to_owned(),
        }
    }

    /// The statements of `b` into `out`; its tail's value, if it has one.
    fn block(
        &mut self,
        f: &Function,
        b: &Block,
        out: &mut String,
        depth: usize,
    ) -> Result<Option<String>, Ineligible> {
        for s in &b.stmts {
            self.stmt(f, s, out, depth)?;
        }
        match &b.tail {
            Some(t) => Ok(Some(self.expr(f, t, out, depth)?)),
            None => Ok(None),
        }
    }

    fn stmt(
        &mut self,
        f: &Function,
        s: &Stmt,
        out: &mut String,
        depth: usize,
    ) -> Result<(), Ineligible> {
        let pad = "  ".repeat(depth);
        match s {
            Stmt::Let { local, value } => {
                let v = self.expr(f, value, out, depth)?;
                let _ = writeln!(out, "{pad}l{} = {v};", local.index());
            }
            Stmt::Assign {
                local,
                path,
                value,
                at,
            } => {
                if !path.is_empty() {
                    return Err(Self::refuse(f, *at, "it writes a record's field"));
                }
                let v = self.expr(f, value, out, depth)?;
                let _ = writeln!(out, "{pad}l{} = {v};", local.index());
            }
            Stmt::Eval(e) => {
                let v = self.expr(f, e, out, depth)?;
                let _ = writeln!(out, "{pad}(void){v};");
            }
            Stmt::If {
                cond,
                then,
                otherwise,
                ..
            } => {
                let c = self.expr(f, cond, out, depth)?;
                let _ = writeln!(out, "{pad}if ({c}) {{");
                self.block(f, then, out, depth + 1)?;
                if let Some(o) = otherwise {
                    let _ = writeln!(out, "{pad}}} else {{");
                    self.block(f, o, out, depth + 1)?;
                }
                let _ = writeln!(out, "{pad}}}");
            }
            Stmt::Loop { id, cond, body, .. } => {
                let _ = writeln!(out, "{pad}for (;;) {{");
                let c = self.expr(f, cond, out, depth + 1)?;
                let _ = writeln!(out, "{pad}  if (!({c})) break;");
                self.block(f, body, out, depth + 1)?;
                let _ = writeln!(out, "{pad}  nz_continue_{}: ;", id.index());
                let _ = writeln!(out, "{pad}}}");
            }
            Stmt::Break { .. } => {
                let _ = writeln!(out, "{pad}break;");
            }
            Stmt::Continue { target, .. } => {
                let _ = writeln!(out, "{pad}goto nz_continue_{};", target.index());
            }
            Stmt::Return { value, .. } => {
                let v = self.expr(f, value, out, depth)?;
                let _ = writeln!(out, "{pad}return {v};");
            }
            Stmt::Block(b) => {
                self.block(f, b, out, depth)?;
            }
            Stmt::Match(m) => return Err(Self::refuse(f, m.at, "it matches on an enum")),
            Stmt::Scope { at, .. } | Stmt::Spawn { at, .. } => {
                return Err(Self::refuse(f, *at, "it starts tasks"))
            }
        }
        Ok(())
    }

    /// The value of `e`, as a C expression over temporaries written into `out` first.
    fn expr(
        &mut self,
        f: &Function,
        e: &Expr,
        out: &mut String,
        depth: usize,
    ) -> Result<String, Ineligible> {
        let pad = "  ".repeat(depth);
        Ok(match &e.kind {
            ExprKind::Const(k) => match f.constant(*k) {
                Some(Const::Int(n)) if *n == i64::MIN => "(-9223372036854775807L - 1L)".to_owned(),
                Some(Const::Int(n)) => format!("{n}L"),
                Some(Const::Bool(b)) => if *b { "1" } else { "0" }.to_owned(),
                _ => return Err(Self::refuse(f, e.at, "it uses a `Str`")),
            },
            ExprKind::Local(l) => format!("l{}", l.index()),
            ExprKind::Neg(x) => {
                let v = self.expr(f, x, out, depth)?;
                let s = self.site("N0400", "this negation overflows `Int`", e.at);
                let t = self.temp();
                let _ = writeln!(
                    out,
                    "{pad}if ({v} == (-9223372036854775807L - 1L)) NZ_FAIL({s});"
                );
                let _ = writeln!(out, "{pad}long {t} = -{v};");
                t
            }
            ExprKind::Arith { op, lhs, rhs } => {
                let a = self.expr(f, lhs, out, depth)?;
                let b = self.expr(f, rhs, out, depth)?;
                let t = self.temp();
                match op {
                    ArithOp::Add | ArithOp::Sub => {
                        let (sym, noun) = if *op == ArithOp::Add {
                            ("+", "addition")
                        } else {
                            ("-", "subtraction")
                        };
                        let s = self.site("N0400", &format!("this {noun} overflows `Int`"), e.at);
                        // Wrapping in unsigned arithmetic, then the sign rule for overflow.
                        let _ =
                            writeln!(out, "{pad}long {t} = (long)((ulong){a} {sym} (ulong){b});");
                        let cond = if *op == ArithOp::Add {
                            format!("((({a}) ^ {t}) & (({b}) ^ {t})) < 0")
                        } else {
                            format!("((({a}) ^ ({b})) & (({a}) ^ {t})) < 0")
                        };
                        let _ = writeln!(out, "{pad}if ({cond}) NZ_FAIL({s});");
                    }
                    ArithOp::Mul => {
                        let s = self.site("N0400", "this multiplication overflows `Int`", e.at);
                        let _ = writeln!(out, "{pad}long {t} = (long)((ulong){a} * (ulong){b});");
                        let _ = writeln!(
                            out,
                            "{pad}if (mul_hi({a}, {b}) != ({t} >> 63)) NZ_FAIL({s});"
                        );
                    }
                    ArithOp::Div | ArithOp::Rem => {
                        let sym = if *op == ArithOp::Div { "/" } else { "%" };
                        // The interpreter's own words for both (`docs/spec.md`).
                        let z = self.site("N0401", "division by zero", e.at);
                        let _ = writeln!(out, "{pad}if ({b} == 0L) NZ_FAIL({z});");
                        if *op == ArithOp::Div {
                            let s = self.site("N0400", "this division overflows `Int`", e.at);
                            let _ = writeln!(out, "{pad}if ({a} == (-9223372036854775807L - 1L) && {b} == -1L) NZ_FAIL({s});");
                            let _ = writeln!(out, "{pad}long {t} = {a} {sym} {b};");
                        } else {
                            // `i64::MIN % -1` is 0 by the spec, and C leaves it undefined.
                            let _ =
                                writeln!(out, "{pad}long {t} = ({b} == -1L) ? 0L : {a} {sym} {b};");
                        }
                    }
                }
                t
            }
            ExprKind::Compare { op, lhs, rhs, .. } => {
                let a = self.expr(f, lhs, out, depth)?;
                let b = self.expr(f, rhs, out, depth)?;
                let sym = match op {
                    CmpOp::Eq => "==",
                    CmpOp::NotEq => "!=",
                    CmpOp::Lt => "<",
                    CmpOp::LtEq => "<=",
                    CmpOp::Gt => ">",
                    CmpOp::GtEq => ">=",
                };
                format!("(({a}) {sym} ({b}))")
            }
            ExprKind::Call { callee, args, .. } => {
                let g = *callee;
                let mut vs = Vec::new();
                for a in args {
                    vs.push(self.expr(f, a, out, depth)?);
                }
                let t = self.temp();
                let _ = writeln!(
                    out,
                    "{pad}long {t} = nz_f{}({}{}nz_fail, nz_index, nz_failed);",
                    g.index(),
                    vs.join(", "),
                    if vs.is_empty() { "" } else { ", " }
                );
                let _ = writeln!(out, "{pad}if (*nz_failed) return 0;");
                t
            }
            ExprKind::If {
                cond,
                then,
                otherwise,
            } => {
                let c = self.expr(f, cond, out, depth)?;
                let t = self.temp();
                let _ = writeln!(out, "{pad}long {t} = 0;");
                let _ = writeln!(out, "{pad}if ({c}) {{");
                if let Some(v) = self.block(f, then, out, depth + 1)? {
                    let _ = writeln!(out, "{pad}  {t} = {v};");
                }
                let _ = writeln!(out, "{pad}}} else {{");
                if let Some(v) = self.block(f, otherwise, out, depth + 1)? {
                    let _ = writeln!(out, "{pad}  {t} = {v};");
                }
                let _ = writeln!(out, "{pad}}}");
                t
            }
            ExprKind::Block(b) => {
                let t = self.temp();
                let _ = writeln!(out, "{pad}long {t} = 0;");
                let _ = writeln!(out, "{pad}{{");
                if let Some(v) = self.block(f, b, out, depth + 1)? {
                    let _ = writeln!(out, "{pad}  {t} = {v};");
                }
                let _ = writeln!(out, "{pad}}}");
                t
            }
            ExprKind::Builtin { op, .. } => {
                return Err(Self::refuse(
                    f,
                    e.at,
                    &format!(
                        "it calls the built-in `{}`, which has no device form",
                        op.name()
                    ),
                ))
            }
            ExprKind::Record { .. }
            | ExprKind::Variant { .. }
            | ExprKind::Field { .. }
            | ExprKind::Match(_) => {
                return Err(Self::refuse(f, e.at, "it uses a record or an enum"))
            }
            ExprKind::Closure { .. } | ExprKind::FnValue(_) | ExprKind::CallIndirect { .. } => {
                return Err(Self::refuse(f, e.at, "it uses a function value"))
            }
            ExprKind::CallTrait { .. } => {
                return Err(Self::refuse(
                    f,
                    e.at,
                    "it calls a method through a type parameter's bound",
                ))
            }
        })
    }
}
