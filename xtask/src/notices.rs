//! `cargo xtask notices` (0.3.0 preview, `docs/user/licensing.md`, item 7): the third-party licence texts
//! and notices a shipped toolchain binary owes, generated from the lockfile it is built from.
//!
//! The crates are the ones `bin/nazm` and `bin/nazm-mcp` **link**: the normal dependencies of
//! `nazm-cli` and `nazm-mcp`, transitively, resolved for `aarch64-apple-darwin` — no build script,
//! procedural macro or test-only crate, none of which travels in a binary. For each, its licence
//! expression and authors, and every licence or notice file it ships, verbatim; a text two crates
//! ship identically is printed once and referred to.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use serde_json::Value;

/// The binaries a release ships, by package.
const SHIPPED: &[&str] = &["nazm-cli", "nazm-mcp"];
/// The one target the 0.9.0 preview supports.
const TARGET: &str = "aarch64-apple-darwin";

pub(crate) fn run(args: &[String]) -> ExitCode {
    let out = args
        .iter()
        .position(|a| a == "--out")
        .and_then(|i| args.get(i + 1))
        .map_or_else(|| PathBuf::from("THIRD-PARTY-NOTICES.md"), PathBuf::from);
    match generate() {
        Ok(text) => match std::fs::write(&out, text) {
            Ok(()) => {
                println!("{} written", out.display());
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("{}: {e}", out.display());
                ExitCode::FAILURE
            }
        },
        Err(e) => {
            eprintln!("notices: {e}");
            ExitCode::FAILURE
        }
    }
}

/// `cargo xtask check`'s step: the committed `THIRD-PARTY-NOTICES.md` is what the lockfile
/// generates, so a dependency changed without regenerating it is caught before a release ships it.
pub(crate) fn check(root: &Path) -> Result<(), Vec<String>> {
    let want = generate().map_err(|e| vec![e])?;
    let have = std::fs::read_to_string(root.join("THIRD-PARTY-NOTICES.md"))
        .map_err(|e| vec![format!("THIRD-PARTY-NOTICES.md: {e}")])?;
    if have == want {
        Ok(())
    } else {
        Err(vec![
            "THIRD-PARTY-NOTICES.md is not what Cargo.lock generates: run `cargo xtask notices`"
                .to_owned(),
        ])
    }
}

struct Crate {
    name: String,
    version: String,
    license: String,
    authors: Vec<String>,
    repository: Option<String>,
    files: Vec<(String, String)>,
}

/// The whole document.
pub(crate) fn generate() -> Result<String, String> {
    let meta = metadata()?;
    let linked = linked(&meta)?;
    let mut crates: Vec<Crate> = linked.into_iter().map(|p| describe(&p)).collect();
    crates.sort_by(|a, b| (&a.name, &a.version).cmp(&(&b.name, &b.version)));
    let mut seen: BTreeMap<String, String> = BTreeMap::new();
    let mut out = String::new();
    out.push_str(
        "# Third-party notices\n\n\
         `bin/nazm` and `bin/nazm-mcp`, as built for `aarch64-apple-darwin` from this repository's \
         `Cargo.lock`, link the crates below. Each is listed with its licence expression and \
         authors as its manifest states them, followed by every licence or notice file it ships, \
         verbatim; a text another crate ships identically is referred to rather than repeated. \
         Nazm itself is licensed under `Apache-2.0 WITH LLVM-exception` (`LICENSE`, `NOTICE`).\n\n\
         Generated by `cargo xtask notices`; do not edit by hand.\n\n",
    );
    out.push_str(&format!("{} crates.\n\n", crates.len()));
    for c in &crates {
        out.push_str(&format!("## {} {}\n\n", c.name, c.version));
        out.push_str(&format!("- Licence: `{}`\n", c.license));
        if !c.authors.is_empty() {
            out.push_str(&format!("- Authors: {}\n", c.authors.join(", ")));
        }
        if let Some(r) = &c.repository {
            out.push_str(&format!("- Source: {r}\n"));
        }
        if c.files.is_empty() {
            out.push_str(
                "- The crate ships no licence file; its terms are the licence expression above.\n",
            );
        }
        out.push('\n');
        for (file, text) in &c.files {
            let key = blake3::hash(text.trim().as_bytes()).to_hex().to_string();
            match seen.get(&key) {
                Some(first) => {
                    out.push_str(&format!("`{file}`: the same text as {first}.\n\n"));
                }
                None => {
                    seen.insert(key, format!("`{file}` of {} {}", c.name, c.version));
                    out.push_str(&format!(
                        "### `{file}`\n\n````text\n{}\n````\n\n",
                        text.trim_end()
                    ));
                }
            }
        }
    }
    Ok(out)
}

fn metadata() -> Result<Value, String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("no repository root")?;
    let out = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_owned()))
        .current_dir(root)
        .args([
            "metadata",
            "--format-version",
            "1",
            "--locked",
            "--filter-platform",
            TARGET,
        ])
        .output()
        .map_err(|e| format!("cargo metadata: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "cargo metadata: {}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    serde_json::from_slice(&out.stdout).map_err(|e| format!("cargo metadata: {e}"))
}

/// The third-party packages the shipped binaries link: normal dependencies, transitively.
fn linked(meta: &Value) -> Result<Vec<Value>, String> {
    let packages: BTreeMap<&str, &Value> = meta["packages"]
        .as_array()
        .ok_or("no packages")?
        .iter()
        .filter_map(|p| Some((p["id"].as_str()?, p)))
        .collect();
    let nodes: BTreeMap<&str, &Value> = meta
        .get("resolve")
        .and_then(|r| r.get("nodes"))
        .and_then(Value::as_array)
        .ok_or("no resolve graph")?
        .iter()
        .filter_map(|n| Some((n["id"].as_str()?, n)))
        .collect();
    let mut work: Vec<&str> = packages
        .iter()
        .filter(|(_, p)| SHIPPED.contains(&p["name"].as_str().unwrap_or("")))
        .map(|(id, _)| *id)
        .collect();
    if work.len() != SHIPPED.len() {
        return Err(format!("expected the packages {SHIPPED:?}"));
    }
    let mut reached: BTreeSet<&str> = BTreeSet::new();
    while let Some(id) = work.pop() {
        if !reached.insert(id) {
            continue;
        }
        let Some(node) = nodes.get(id) else { continue };
        for dep in node["deps"].as_array().into_iter().flatten() {
            let normal = dep["dep_kinds"]
                .as_array()
                .into_iter()
                .flatten()
                .any(|k| k["kind"].is_null());
            if normal {
                if let Some(d) = dep["pkg"].as_str() {
                    work.push(d);
                }
            }
        }
    }
    Ok(reached
        .into_iter()
        .filter_map(|id| packages.get(id).copied())
        // The workspace's own crates are Nazm's, under its own licence.
        .filter(|p| !p["source"].is_null())
        .cloned()
        .collect())
}

fn describe(p: &Value) -> Crate {
    let s = |k: &str| p[k].as_str().map(str::to_owned);
    let dir = s("manifest_path")
        .map(PathBuf::from)
        .and_then(|m| m.parent().map(Path::to_path_buf));
    let mut files = Vec::new();
    if let Some(dir) = dir {
        let mut names: Vec<PathBuf> = std::fs::read_dir(&dir)
            .into_iter()
            .flatten()
            .flatten()
            .map(|e| e.path())
            .filter(|f| {
                f.is_file()
                    && f.file_name().and_then(|n| n.to_str()).is_some_and(|n| {
                        let n = n.to_ascii_uppercase();
                        [
                            "LICENSE",
                            "LICENCE",
                            "COPYING",
                            "NOTICE",
                            "UNLICENSE",
                            "COPYRIGHT",
                        ]
                        .iter()
                        .any(|w| n.starts_with(w))
                    })
            })
            .collect();
        names.sort();
        for f in names {
            if let Ok(text) = std::fs::read_to_string(&f) {
                let name = f
                    .file_name()
                    .and_then(|n| n.to_str())
                    .unwrap_or("LICENSE")
                    .to_owned();
                files.push((name, text));
            }
        }
    }
    Crate {
        name: s("name").unwrap_or_default(),
        version: s("version").unwrap_or_default(),
        license: s("license").unwrap_or_else(|| "(none stated)".to_owned()),
        authors: p["authors"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(|a| a.as_str().map(str::to_owned))
            .collect(),
        repository: s("repository"),
        files,
    }
}
